test('old exercise history stays accessible in lessons and returns to its source', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.topbar')).toBeVisible()
  const lessonTitle = await page.evaluate(() => {
    const store = JSON.parse(localStorage.getItem('linguanest_workspace_v2')!)
    const doc = store.documents[0]
    const unlinked = { ...doc, id: 'unlinked-exercise', lesson_id: null, title: 'Unlinked legacy practice' }
    store.documents.push(unlinked); store.exams.push(unlinked)
    const now = new Date().toISOString()
    const makeRun = (d: typeof doc, id: string) => ({
      id, exam_id: d.id, title: d.title, language_code: d.language_code, version: 1,
      media_keys: [], questions: d.questions, responses: {}, started_at: now, deadline: null,
      submitted_at: now, status: 'graded', score: 1, max_score: d.questions.reduce((total: number, q: { points: number }) => total + q.points, 0),
      revision: 0, grades: {}, user_id: 'demo',
    })
    localStorage.setItem('linguanest_workspace_v2', JSON.stringify(store))
    localStorage.setItem('linguanest_runs_v2', JSON.stringify([makeRun(doc, 'linked-old'), makeRun(unlinked, 'unlinked-old')]))
    return store.lessons.find((l: { id: string }) => l.id === doc.lesson_id).title
  })
  await page.reload(); await nav(page, 'Tiến độ & lịch sử')
  await expect(page.getByRole('heading', { name: '0 XP từ đề thi' })).toBeVisible()
  await expect(page.getByText('Unlinked legacy practice', { exact: true })).toHaveCount(0)
  await nav(page, 'Bài học')
  const legacy = page.locator('.legacy-practice-history')
  await expect(legacy).toContainText('Bài tập cũ chưa gắn bài học')
  await legacy.getByRole('button', { name: 'Xem bài tập cũ' }).click()
  await expect(page.getByRole('heading', { name: 'Unlinked legacy practice' })).toBeVisible()
  await page.getByRole('button', { name: '← Về danh sách bài học', exact: true }).click()
  await expect(legacy).toContainText('Bài tập cũ chưa gắn bài học')
  const lesson = page.locator('.lesson-row').filter({ hasText: lessonTitle })
  await expect(lesson).toHaveClass(/study-completed/)
  await lesson.click()
  await expect(legacy).toContainText('Lịch sử bài tập cũ')
  await legacy.getByRole('button', { name: 'Xem bài tập cũ' }).click()
  await page.getByRole('button', { name: '← Quay về bài học', exact: true }).click()
  await expect(page.locator('.lesson-hero')).toContainText(lessonTitle)
})
