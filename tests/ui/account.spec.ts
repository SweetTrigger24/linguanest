  await expect(page.getByText('Đã lưu hồ sơ.', { exact: true })).toBeVisible()
  await expect(page.locator('.side-user img')).toHaveCount(1)
  await expect(page.locator('.side-user')).toContainText('Linh học ngoại ngữ')
