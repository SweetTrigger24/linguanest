  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function(key, value) {
      if (key === 'linguanest_profile_v2') { Storage.prototype.setItem = original; throw new Error('Không lưu được hồ sơ thử nghiệm.') }
      return original.call(this, key, value)
    }
  })
  await page.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Không lưu được hồ sơ thử nghiệm.')
  await expect(page.locator('.profile-avatar img')).toBeVisible()
  await expect(page.locator('.side-user img')).toHaveCount(0)
