test('lesson drafts restore, invalid CSV is rejected, and archived lessons disappear', async ({ page }) => {
  await page.goto('/'); await nav(page, 'Quản trị')
  await page.getByRole('button', { name: '+ Tạo bài học', exact: true }).click()
  await page.getByLabel('Tiêu đề', { exact: true }).fill('Bài học bản nháp')
  await page.getByLabel('Nội dung bài giảng').fill('Đoạn một.\n\nĐoạn hai.')
  await expect(page.getByText(/Đã lưu bản nháp trên máy lúc/)).toBeVisible()
  await page.waitForTimeout(600)
  await page.reload(); await nav(page, 'Quản trị'); await page.getByRole('button', { name: '+ Tạo bài học', exact: true }).click()
  await expect(page.getByLabel('Tiêu đề', { exact: true })).toHaveValue('Bài học bản nháp')
  await page.getByLabel('Nhập CSV').setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from('term,meaning\nhello,\n') })
  await expect(page.getByRole('button', { name: 'Thêm vào bản nháp' })).toBeDisabled()
  await page.getByLabel('Nhập CSV').setInputFiles({ name: 'words.csv', mimeType: 'text/csv', buffer: Buffer.from('term,meaning\nhello,xin chào\n') })
  await page.getByRole('button', { name: 'Thêm vào bản nháp' }).click()
  await page.getByRole('button', { name: 'Lưu nội dung', exact: true }).click()
  await nav(page, 'Bài học'); await expect(page.getByRole('button', { name: /Bài học bản nháp/ })).toHaveCount(0)
  await nav(page, 'Quản trị'); await page.getByLabel('Tìm nội dung').fill('Bài học bản nháp')
  await page.getByRole('button', { name: 'Sửa / xem trước', exact: true }).click()
  await page.getByLabel('Trạng thái').selectOption('published'); await page.getByRole('button', { name: 'Lưu và xuất bản', exact: true }).click()
  await nav(page, 'Bài học'); await page.getByRole('button', { name: /Bài học bản nháp/ }).click()
  await expect(page.getByText('hello', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Đánh dấu hoàn thành/ }).click(); await expect(page.getByRole('button', { name: '✓ Đã hoàn thành' })).toBeDisabled()
  await nav(page, 'Quản trị'); await page.getByLabel('Tìm nội dung').fill('Bài học bản nháp'); await page.getByRole('button', { name: 'Sửa / xem trước', exact: true }).click()
  await page.getByLabel('Trạng thái').selectOption('archived'); await page.getByRole('button', { name: 'Lưu nội dung', exact: true }).click()
  await nav(page, 'Bài học'); await expect(page.getByRole('button', { name: /Bài học bản nháp/ })).toHaveCount(0)
  await nav(page, 'Tiến độ & lịch sử'); await expect(page.getByRole('heading', { name: '0 XP từ đề thi' })).toBeVisible(); await expect(page.locator('.topbar-streak')).toContainText('20 XP')
})
